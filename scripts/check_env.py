"""Environment check: Python version, required/optional packages, and (optionally) a lock file of the versions that work for you.
Usage:  python scripts/check_env.py            -> report
        python scripts/check_env.py --lock     -> also write requirements.lock.txt from `pip freeze` (do this AFTER the tests pass)"""
import importlib
import importlib.metadata as md
import subprocess
import sys

REQUIRED = {"fastapi": "fastapi", "uvicorn": "uvicorn"}
TEST = {"pytest": "pytest", "httpx": "httpx"}
DESKTOP = {"webview": "pywebview", "PyInstaller": "pyinstaller"}
OPTIONAL = {"keyring": "keyring", "yara": "yara-python"}


def check(group, title):
    print(f"\n{title}")
    bad = 0
    for mod, dist in group.items():
        try:
            importlib.import_module(mod)
            print(f"  OK       {dist} {md.version(dist)}")
        except Exception as e:
            bad += 1
            print(f"  MISSING  {dist} ({type(e).__name__})")
    return bad


def main():
    v = sys.version_info
    print(f"Python {v.major}.{v.minor}.{v.micro} on {sys.platform}")
    if v < (3, 10):
        print("  ERROR: EmailShield needs Python 3.10 or newer.")
    elif v >= (3, 14):
        print("  NOTE: 3.14 is very new. If a package fails to install, retry with Python 3.12 (py -3.12 -m venv venv312).")
    missing = check(REQUIRED, "Required to run") + check(TEST, "Required to test")
    check(DESKTOP, "Desktop window / building the .exe (optional)")
    check(OPTIONAL, "Optional features")
    if "--lock" in sys.argv and not missing:
        out = subprocess.run([sys.executable, "-m", "pip", "freeze"], capture_output=True, text=True, check=True).stdout
        open("requirements.lock.txt", "w").write("# Generated by scripts/check_env.py --lock on a working environment. Use for reproducible installs.\n" + out)
        print("\nWrote requirements.lock.txt (install later with: pip install -r requirements.lock.txt)")
    return 1 if missing else 0


if __name__ == "__main__":
    raise SystemExit(main())

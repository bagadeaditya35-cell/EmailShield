"""Generates docs/DETECTION_RULES.md from the ACTUAL detector (so the documentation cannot drift from the code)."""
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))
from emailshield import __version__, config, detector  # noqa: E402

INPUT = {"sender": "From / Reply-To / Return-Path headers and display name", "auth": "Authentication-Results / Received-SPF headers",
         "url": "URLs (and visible link text) extracted from the body and HTML", "content": "Subject and body text keywords",
         "attachment": "Attachment file name, declared type, magic bytes, size, optional YARA match", "structure": "Whether the file parses as an email at all"}
L = [f"# Detection rules (generated from EmailShield {__version__}; ruleset fingerprint `{detector.ruleset_version()}`)", "",
     "Generated by `scripts/gen_rule_docs.py`. Scores are heuristic; each group's total is capped so one underlying condition cannot stack. Thresholds: "
     f"Suspicious >= {config.THRESHOLDS['suspicious']}, High risk >= {config.THRESHOLDS['high']}.", "",
     "| Rule id | Group | Weight | Rule version | What it inspects | Finding |", "|---|---|---|---|---|---|"]
for rid in sorted(detector.TITLES, key=lambda r: (detector.group_of(r), -config.WEIGHTS.get(r, 0))):
    g = detector.group_of(rid)
    L.append(f"| `{rid}` | {g} | {config.WEIGHTS.get(rid, 0)} | {detector.RULE_VERSIONS.get(rid, '1')} | {INPUT[g]} | {detector.TITLES[rid]} |")
L += ["", "## Group caps", "", "| Group | Cap |", "|---|---|"] + [f"| {g} | {c} |" for g, c in config.GROUP_CAPS.items()]
L += ["", "## What every stored finding contains", "rule id, title, points, severity, group, reason, evidence (the matched values), recommended next step, rule version; "
      "every scan also stores engine version, ruleset fingerprint, score, category and timestamp. MITRE ATT&CK mappings are derived from fired rules (see attack.py).",
      "", "## What the engine does NOT do", "Content/semantic analysis, image/QR analysis, sandboxing, URL fetching, reputation lookups (unless the optional threat-intel providers are enabled), or any action on the mailbox."]
(ROOT / "docs" / "DETECTION_RULES.md").write_text("\n".join(L) + "\n")
print(f"wrote docs/DETECTION_RULES.md ({len(detector.TITLES)} rules)")

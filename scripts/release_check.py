"""Release-readiness gate. Checks secrets, forbidden files, .gitignore, required docs, licence decision, version consistency and the
recorded real-world evidence (docs/RELEASE_EVIDENCE.json). Writes docs/RELEASE_READINESS.md.
Usage: python scripts/release_check.py [--label experimental|beta]   (exit 1 if the requested label is not justified)
It can only verify the repository; it cannot verify the evidence file's claims, so keep that file honest."""
import json
import re
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))
from emailshield import __version__  # noqa: E402

REQUIRED_DOCS = ["README.md", "PROGRESS.md", "SECURITY.md", ".env.example", ".gitignore", "docs/MONITORING.md", "docs/DATABASE_MIGRATIONS.md", "docs/SPLUNK.md",
                 "docs/TEST_PLAN_AND_RESULTS.md", "docs/ARCHITECTURE.md", "docs/THREAT_MODEL.md", "docs/PRIVACY.md", "docs/WINDOWS_INSTALLATION.md",
                 "docs/GITHUB_RELEASE.md", "docs/BACKUP_AND_RECOVERY.md", "docs/MULTI_ACCOUNT_AND_USERS.md", "docs/GMAIL_OAUTH_TROUBLESHOOTING.md",
                 "docs/DETECTION_RULES.md", "docs/DETECTION_EVALUATION.md", "docs/RELEASE_NOTES.md"]
GITIGNORE_NEEDS = ["data/", "*.db", "secrets.json", "api_key.txt", "gmail_token.json", "client_secret*.json", ".env", "*.log", "venv/", "dist/", "*.pem"]
BETA_EVIDENCE = ["pytest_real_run", "windows_build_done", "installer_tested_clean_machine", "upgrade_tested", "uninstall_tested"]


def sh(*a):
    r = subprocess.run(a, cwd=ROOT, capture_output=True, text=True, errors="replace")
    return r.returncode, r.stdout


def main():
    label = sys.argv[sys.argv.index("--label") + 1] if "--label" in sys.argv else "experimental"
    rows, blockers, warnings = [], [], []

    def add(name, ok, detail, blocker=True):
        rows.append((name, "PASS" if ok else ("FAIL" if blocker else "WARN"), detail))
        if not ok:
            (blockers if blocker else warnings).append(f"{name}: {detail}")

    code, out = sh(sys.executable, "scripts/secret_scan.py", "--history")
    add("Secret scan (tree + full git history)", code == 0, out.strip().splitlines()[1] if out.strip() else "scan failed")
    code, tracked = sh("git", "ls-files")
    bad = [f for f in tracked.splitlines() if re.search(r"(^|/)(data/|.*\.db$|secrets\.json$|api_key\.txt$|gmail_token\.json$|\.env$|.*\.pem$)", f)]
    add("No private/data files tracked", not bad, ", ".join(bad) or "none tracked")
    gi = (ROOT / ".gitignore").read_text() if (ROOT / ".gitignore").exists() else ""
    miss = [p for p in GITIGNORE_NEEDS if p not in gi]
    add(".gitignore covers secrets, data, logs, builds", not miss, "missing: " + ", ".join(miss) if miss else "ok")
    missing_docs = [d for d in REQUIRED_DOCS if not (ROOT / d).exists()]
    add("Required documentation present", not missing_docs, "missing: " + ", ".join(missing_docs) if missing_docs else f"{len(REQUIRED_DOCS)} files")
    env = (ROOT / ".env.example").read_text() if (ROOT / ".env.example").exists() else ""
    real = [l for l in env.splitlines() if re.match(r"^[A-Z_]+=\S+", l) and not re.search(r"<[^>]+>|^[A-Z_]+=(true|false|\d+|127\.0\.0\.1)$", l)]
    add(".env.example has placeholders only", not real, "suspicious lines: " + "; ".join(real) if real else "ok")
    add("Licence decided", (ROOT / "LICENSE").exists(), "no LICENSE file (all rights reserved): decide first, see docs/LICENSE_CONSIDERATIONS.md", blocker=False)
    readme = (ROOT / "README.md").read_text() if (ROOT / "README.md").exists() else ""
    add("README names the current version", __version__ in readme, f"README does not mention {__version__}")
    add("README does not claim production approval", not re.search(r"(?i)production[- ]ready|government[- ]approved|certified", re.sub(r"(?i)not (yet )?(production[- ]ready|government[- ]approved|certified)", "", readme)), "check wording")
    ev = json.loads((ROOT / "docs" / "RELEASE_EVIDENCE.json").read_text())
    missing_ev = [k for k in BETA_EVIDENCE if not ev.get(k)]
    add("Evidence for 'beta' recorded (real pytest, Windows build, installer, upgrade, uninstall)", not missing_ev,
        "not recorded: " + ", ".join(missing_ev) if missing_ev else "all recorded (unverifiable by this script)", blocker=(label == "beta"))
    unverified = [k for k in ("gmail_live_tested", "two_accounts_live_tested", "splunk_live_tested", "benchmark_on_target_laptop") if not ev.get(k)]

    repo_ok = not any(b for b in blockers if not b.startswith("Evidence"))
    recommended = "beta" if (repo_ok and not missing_ev) else "experimental"
    L = [f"# Release readiness report (EmailShield {__version__}, generated by scripts/release_check.py)", "",
         f"**Recommended label: {recommended.upper()}**   (requested: {label}; 'stable' is never recommended by this tool)", "",
         "| Check | Result | Detail |", "|---|---|---|"] + [f"| {n} | {r} | {d} |" for n, r, d in rows]
    L += ["", "## Features not verified live (per evidence file)", *([f"- {u}" for u in unverified] or ["- none"]), "",
          "## Blockers", *([f"- {b}" for b in blockers] or ["- none for the requested label"]), "", "## Warnings", *([f"- {w}" for w in warnings] or ["- none"]),
          "", "This report checks the repository and a self-reported evidence file only. It is not a security review or an approval for confidential data."]
    (ROOT / "docs" / "RELEASE_READINESS.md").write_text("\n".join(L) + "\n")
    print("\n".join(L[:3 + len(rows) + 2]))
    print(f"\nrecommended label: {recommended}; blockers for '{label}': {len(blockers)}")
    return 1 if blockers else 0


if __name__ == "__main__":
    raise SystemExit(main())
